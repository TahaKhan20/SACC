def _extract_value(entity: dict[str, Any]) -> str:
    """Extract the string value from a DocumentEntity record."""
    return (
        entity.get("stringValue")
        or str(entity.get("numberValue", "") or "")
        or entity.get("dateValue", "")
        or entity.get("rawValue", "")
        or ""
    )


def _build_lookup(extraction: list[dict[str, Any]]) -> dict[str, str]:
    """Build a name->value lookup from a list of DocumentEntity records."""
    lookup: dict[str, str] = {}
    for entity in extraction:
        name = entity.get("name", "")
        value = _extract_value(entity)
        if name and value:
            lookup[name] = str(value)
    return lookup


# -- Step 1: Upload Document --------------------------------------------------

def upload_document(state: TriageState) -> TriageState:
    """Upload the source document file to Document AI."""
    logger.info("Step 1: Uploading document...")
    file_path = state.get("file_path", "")
    file_name = state.get("file_name", "")
    evidence = state.get("evidence", [])

    client = _get_doc_ai_client()

    # Read file content if path is provided
    file_content = None
    if file_path and os.path.isfile(file_path):
        with open(file_path, "rb") as f:
            file_content = f.read()
        if not file_name:
            file_name = os.path.basename(file_path)
        evidence.append(f"File loaded from disk: {file_name} ({len(file_content)} bytes)")
    elif not file_name:
        file_name = "unknown_document.pdf"
        evidence.append("No file path provided -- using placeholder name")

    # Upload file (mocked -- see DocAIApiClient.upload_file for details)
    file_record = client.upload_file(file_name, file_content or b"")
    file_id = file_record.get("ID", str(uuid.uuid4()))

    # Create Document record
    doc_id = str(uuid.uuid4())
    client.create_document({
        "ID": doc_id,
        "status": "PENDING",
        "file_ID": file_id,
        "clientId": SAP_DOCAI_CLIENT_ID,
    })

    evidence.append(f"Document created with ID={doc_id}, file_ID={file_id}")
    logger.info("Document uploaded: ID=%s", doc_id)

    return {**state, "document_id": doc_id, "file_id": file_id,
            "file_name": file_name, "evidence": evidence}


