"""AP Invoice Triage Agent (Plain Python -- no LangGraph)
======================================================

A production-ready pipeline that triages AP invoices using the SAP Document AI
(Document Information Extraction) mock APIs generated by the SACC project,
plus the Supplier Invoice OData mock API.

Workflow (11 steps):
    1.  START -> upload document (real PDF bytes via base64 to Files entity)
    2.  Call Document API to get extraction results for classification
    3.  Determine Document Type using shared keywords from keywords.json
        (Invoice, Credit Note, Supporting Document, Statement of Account,
         Reconciliation, Purchase Order List, General Correspondence)
    4.  If not invoice/credit_note/statement -> REVIEW / END
    5.  Classify company: Saudia Cargo vs Saudia Airline
        - Saudia Airline if PO number starts with '62' AND vendor number
          starts with '15' (checked first, returns early)
        - Otherwise Saudia Cargo
    6.  If company does not match -> REVIEW
    7.  Determine DIRECT vs INTERCOMPANY
    8.  Determine invoice type: FUEL | CHARTER | SERVICE | OTHER
    9.  Extract detailed header fields and line items
    10. Validate extraction confidence / required fields
    11. Build and return TriageResult

All API URLs, credentials, company config, and model config
are read from environment variables (see .env.example).

Shared document type categories are loaded from
langgraph/document_types.json — single source of truth used by both
EmailIntakeAgent and TriageAgent.
"""

