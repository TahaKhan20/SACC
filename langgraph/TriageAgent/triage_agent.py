# TriageState is just a dict[str, Any]. Each step function takes the current
# state dict and returns an updated dict.


class TriageState(dict):
    """Mutable dict subclass used as the pipeline state.

    Acts like a normal dict but with attribute-style access for convenience.
    """
    def __getattr__(self, key: str) -> Any:
        try:
            return self[key]
        except KeyError:
            raise AttributeError(key)

    def __setattr__(self, key: str, value: Any) -> None:
        self[key] = value


# -- API Client: Document Information Extraction -----------------------------


class DocAIApiClient:
    """Client for the Document Information Extraction mock API."""

    def __init__(self, base_url: str = API_BASE_URL):
        self.base_url = base_url.rstrip("/")
        self.service = DOC_AI_SERVICE
        self.client = httpx.Client(timeout=30.0)

    def _url(self, entity_set: str, suffix: str = "") -> str:
        path = f"/api/services/{self.service}/entities/{entity_set}"
        if suffix:
            path += suffix
        return f"{self.base_url}{path}"

    # -- Documents ----------------------------------------------------------

    def create_document(self, payload: dict[str, Any]) -> dict[str, Any]:
        """Create a Document record (Step 1: upload document)."""
        resp = self.client.post(self._url("Documents"), json=payload)
        resp.raise_for_status()
        return resp.json()

    def get_document(self, doc_id: str) -> dict[str, Any]:
        """Read a Document record by ID."""
        resp = self.client.get(self._url("Documents", "/item"), params={"ID": doc_id})
        resp.raise_for_status()
        return resp.json()

    def list_documents(self) -> list[dict[str, Any]]:
        """List all Document records."""
        resp = self.client.get(self._url("Documents"))
        resp.raise_for_status()
        return resp.json()

    def update_document(self, doc_id: str, updates: dict[str, Any]) -> dict[str, Any]:
        """Update a Document record (e.g. set schema_ID, status)."""
        resp = self.client.patch(self._url("Documents", "/item"), params={"ID": doc_id}, json=updates)
        resp.raise_for_status()
        return resp.json()

    # -- Files --------------------------------------------------------------

    def get_file(self, file_id: str) -> dict[str, Any]:
        """Read a File record by ID."""
        resp = self.client.get(self._url("Files", "/item"), params={"ID": file_id})
        resp.raise_for_status()
        return resp.json()

    def upload_file(self, file_name: str, file_content: bytes) -> dict[str, Any]:
        """Upload a file to Document AI via the SACC mock API.

        Sends the actual PDF bytes (base64-encoded) to the Files entity
        via POST.  Requires the SACC mock API to be running and the
        Files entity to be insertable (see EDMX configuration).
        """
        import base64
        file_id = str(uuid.uuid4())
        payload = {
            "ID": file_id,
            "name": file_name,
            "contentBytes": base64.b64encode(file_content).decode("utf-8"),
            "size": len(file_content),
        }
        resp = self.client.post(self._url("Files"), json=payload)
        resp.raise_for_status()
        file_record = resp.json()
        logger.info(
            "File uploaded to mock API: ID=%s, name=%s, size=%d bytes",
            file_record.get("ID"), file_name, len(file_content),
        )
        return file_record

    # -- SchemaVersions ----------------------------------------------------

    def create_schema_version(self, payload: dict[str, Any]) -> dict[str, Any]:
        """Create a SchemaVersion record (Step 2: upload schema)."""
        resp = self.client.post(self._url("SchemaVersions"), json=payload)
