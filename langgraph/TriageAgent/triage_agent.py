def classify_with_document_api(state: TriageState) -> TriageState:
    """Call Document API to get initial extraction results for classification."""
    logger.info("Step 2: Calling Document API...")
    evidence = state.get("evidence", [])
    doc_id = state.get("document_id", "")
    client = _get_doc_ai_client()

    # Update the Document record to trigger processing
