@dataclass
class TriageResult:
    """Strict JSON TriageResult returned at the end of the workflow."""
    document_type: str
    company_classification: str
    direct_intercompany: str
    invoice_type: str
    extracted_header_fields: dict[str, Any]
    line_items: list[dict[str, Any]]
    confidence: float
    evidence: list[str]
    review_required: bool
    review_reason: Optional[str]

    def to_dict(self) -> dict[str, Any]:
        return {
            "document_type": self.document_type,
            "company_classification": self.company_classification,
            "direct_intercompany": self.direct_intercompany,
            "invoice_type": self.invoice_type,
            "extracted_header_fields": self.extracted_header_fields,
            "line_items": self.line_items,
            "confidence": self.confidence,
            "evidence": self.evidence,
            "review_required": self.review_required,
            "review_reason": self.review_reason,
        }

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2, default=str)


# -- Pipeline State (plain dict) ---------------------------------------------

# TriageState is just a dict[str, Any]. Each step function takes the current
# state dict and returns an updated dict.


class TriageState(dict):
    """Mutable dict subclass used as the pipeline state.

    Acts like a normal dict but with attribute-style access for convenience.
    """
    def __getattr__(self, key: str) -> Any:
        try:
            return self[key]
        except KeyError:
            raise AttributeError(key)

    def __setattr__(self, key: str, value: Any) -> None:
        self[key] = value


